SELECT
    COUNT(*) AS total_stock,
    SUM(cantidad) AS unidades_totales,
    MIN(cantidad) AS stock_minimo,
    MAX(cantidad) AS stock_maximo,
    ROUND(AVG(cantidad), 1) AS stock_promedio
FROM stock
WHERE deleted_at IS NULL;
